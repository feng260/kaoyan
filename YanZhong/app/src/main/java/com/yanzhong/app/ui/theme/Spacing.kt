package com.yanzhong.app.ui.theme

import androidx.compose.ui.unit.dp

/**
 * 间距令牌。
 *
 * 此前全项目 padding/spacedBy 一共用了 27 种 dp 取值(含 3/5/7/9/15/18 这些非 4 倍数),
 * 既看不出层级、也无法判断某个间距是"随手写的"还是"有意为之"。这里收敛成 6 档,
 * 覆盖了原先使用频次最高的 4/8/12/16/24 五档(合计 200+ 次命中):
 *
 * xs  4  —— 图标与紧邻文字、行内小块之间的最小间隙
 * sm  8  —— 同一组内元素之间
 * md 12  —— 卡片内元素之间、列表行之间
 * lg 16  —— 卡片内边距、区块之间
 * xl 24  —— 页面级区块分隔
 * xxl 32 —— 大段留白、空态上下留白
 *
 * 存量代码不做全量替换(那是一次数百处的大爆炸式改动、回归面过宽),
 * 采用"触达即替换":只在本次确实要改动的代码里顺手换成令牌,其余保持原样。
 */
object Spacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
    val xxl = 32.dp
}